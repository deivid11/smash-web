export const LOOKS: readonly LookDefinition[] = [ANIMELEE_LOOK];

/** CLASSICAL_SCALE (JObj flag 0x8) sets how scale inherits down a skeleton, so it moves every posed
 * joint, hurtbox and hit point. Animelee's rebuilt costumes drop it, so a look keeps its own
 * meshes, materials and skinning flags while its costume joints take the original disc's bit.
 * Undefined for looks this build does not know (they are never applied). */
export function lookModelPatch(id: string): ((name: string, model: HsdModel) => void) | undefined {
  const definition = LOOKS.find((look) => look.id === id);
  if (!definition) return undefined;
  const masks = definition.classicalScale ?? {};
  return (name, model) => {
    const hex = masks[name];
    if (hex === undefined) return;
    const mask = BigInt(`0x${hex}`);
    model.roots.flatMap((root) => root.joints).forEach((joint, index) => {
      joint.flags = (joint.flags & ~8) | ((mask >> BigInt(index)) & 1n ? 8 : 0);
    });
  };
}
