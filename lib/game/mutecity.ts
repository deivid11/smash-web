/** splGetSplinePoint (sysdolphin/baselib/spline.c). The u == 1 edges in C read one
 * past the CV array (owned padding in the original heap); the clamp below keeps
 * the same values without the out-of-bounds read. */
export function muteCitySplinePoint(spline: MuteCitySpline, u: number, out: [number, number, number]): boolean {
  if (u < 0 || u > 1) return false;
  const { type, tension, points } = spline;
  const at = (k: number): readonly [number, number, number] => points[Math.min(points.length - 1, Math.max(0, k))]!;
  if (u >= 1) {
    if (type === 1) { const p = at((points.length - 1) * 3); out[0] = p[0]; out[1] = p[1]; out[2] = p[2]; return true; }
    if (type === 2) {
      const n = points.length - 1, p1 = at(n - 1), p2 = at(n), p3 = at(n);
      const k = 1 / 6;
      out[0] = p1[0] * k + p2[0] * (4 * k) + p3[0] * k;
      out[1] = p1[1] * k + p2[1] * (4 * k) + p3[1] * k;
      out[2] = p1[2] * k + p2[2] * (4 * k) + p3[2] * k;
      return true;
    }
    const p = at(points.length - 1);
    out[0] = p[0]; out[1] = p[1]; out[2] = p[2];
    return true;
  }
  const scaled = u * (points.length - 1), idx = Math.floor(scaled), t = scaled - idx;
  if (type === 0) {
    const a = at(idx), b = at(idx + 1);
    out[0] = t * (b[0] - a[0]) + a[0]; out[1] = t * (b[1] - a[1]) + a[1]; out[2] = t * (b[2] - a[2]) + a[2];
    return true;
  }
  if (type === 1) {
    const p0 = at(idx * 3), p1 = at(idx * 3 + 1), p2 = at(idx * 3 + 2), p3 = at(idx * 3 + 3);
    const v = 1 - t, u2 = t * t, v2 = v * v;
    const b0 = v2 * v, b1 = 3 * t * v2, b2 = 3 * u2 * v, b3 = u2 * t;
    out[0] = p0[0] * b0 + p1[0] * b1 + p2[0] * b2 + p3[0] * b3;
    out[1] = p0[1] * b0 + p1[1] * b1 + p2[1] * b2 + p3[1] * b3;
    out[2] = p0[2] * b0 + p1[2] * b1 + p2[2] * b2 + p3[2] * b3;
    return true;
  }
  if (type === 2) {
    const p0 = at(idx), p1 = at(idx + 1), p2 = at(idx + 2), p3 = at(idx + 3);
    const k = 1 / 6, v = 1 - t, u2 = t * t, u3 = u2 * t;
    const b0 = k * v * v * v, b1 = k * (4 + 3 * u3 - 6 * u2), b2 = k * (3 * (-u3 + u2 + t) + 1), b3 = k * u3;
    out[0] = p0[0] * b0 + p1[0] * b1 + p2[0] * b2 + p3[0] * b3;
    out[1] = p0[1] * b0 + p1[1] * b1 + p2[1] * b2 + p3[1] * b3;
    out[2] = p0[2] * b0 + p1[2] * b1 + p2[2] * b2 + p3[2] * b3;
    return true;
  }
  const p0 = at(idx), p1 = at(idx + 1), p2 = at(idx + 2), p3 = at(idx + 3);
  const u2 = t * t, u3 = u2 * t;
  const c0 = tension * (-u3 + 2 * u2 - t), c1 = (2 - tension) * u3 + (tension - 3) * u2 + 1;
  const c2 = (tension - 2) * u3 + (3 - 2 * tension) * u2 + tension * t, c3 = tension * (u3 - u2);
  out[0] = p0[0] * c0 + p1[0] * c1 + p2[0] * c2 + p3[0] * c3;
  out[1] = p0[1] * c0 + p1[1] * c1 + p2[1] * c2 + p3[1] * c3;
  out[2] = p0[2] * c0 + p1[2] * c1 + p2[2] * c2 + p3[2] * c3;
  return true;
}

/** grMc_SplineEvalWrapped: the 0.93-1.0/0.0-0.01 seam is bridged by lerping the
 * 0.93 and 0.01 evaluations (the start/finish straight). */
export function muteCitySplineWrapped(spline: MuteCitySpline, t: number, out: [number, number, number]): void {
  if (t > 0.93 || t < 0.01) {
    const frac = t > 0.93 ? t - 0.93 : 0.06999999 + t;
    const a: [number, number, number] = [0, 0, 0], b: [number, number, number] = [0, 0, 0];
    muteCitySplinePoint(spline, 0.93, a);
    muteCitySplinePoint(spline, 0.01, b);
    const s = frac / 0.07999999;
    out[0] = (b[0] - a[0]) * s + a[0]; out[1] = (b[1] - a[1]) * s + a[1]; out[2] = (b[2] - a[2]) * s + a[2];
    return;
  }
  muteCitySplinePoint(spline, t, out);
}

/** World matrix of one entry-30 joint at an animation frame, replicating
 * ModelInstance.update's per-node math (rest pose, slot-0 animation tracks,
 * classical-scale accumulation) so collision matches the rendered road. */
const scratchA = new Matrix4();
function jointWorldAt(data: MuteCityTrackData, chain: number[], animFrame: number, out: Matrix4): void {
  const acc: [number, number, number] = [1, 1, 1];
  out.identity();
  for (const hare of chain) {
    const joint = data.joints[hare]!;
    const rotation: [number, number, number] = [...joint.rotation];
    const scale: [number, number, number] = [...joint.scale];
    const translation: [number, number, number] = [...joint.translation];
    const anim = data.clip?.joints[hare];
    if (anim) {
      const time = anim.endFrame > 0 ? animFrame % anim.endFrame : 0;
      for (const track of anim.tracks) {
        const value = sampleTrack(track.keys, time);
        if (value === undefined) continue;
        if (track.type >= 1 && track.type <= 3) rotation[track.type - 1] = value;
        else if (track.type >= 5 && track.type <= 7) translation[track.type - 5] = value;
        else if (track.type >= 8 && track.type <= 10) scale[track.type - 8] = value;
      }
    }
    if (joint.inheritScale) { acc[0] = acc[0]; acc[1] = acc[1]; acc[2] = acc[2]; }
    else { acc[0] = scale[0] * acc[0]; acc[1] = scale[1] * acc[1]; acc[2] = scale[2] * acc[2]; }
    // NOTE: inheritScale keeps the parent's accumulation; jointMatrix applies
    // the parent/journal ratio correction from the passed accumulation.
    jointMatrix(scratchA, scale, rotation, translation, acc);
    out.multiply(scratchA);
  }
}

/** lb_8000B1CC: transform a spline-local point by a joint world matrix. */
function transformPoint(matrix: Matrix4, point: [number, number, number], out: [number, number, number]): void {
  const e = matrix.elements;
  out[0] = e[0]! * point[0] + e[4]! * point[1] + e[8]! * point[2] + e[12]!;
  out[1] = e[1]! * point[0] + e[5]! * point[1] + e[9]! * point[2] + e[13]!;
  out[2] = e[2]! * point[0] + e[6]! * point[1] + e[10]! * point[2] + e[14]!;
}

const scratchM = new Matrix4();
/** grMuteCity_801F094C: advance a spline marker to the nearest world z = 0
 * crossing (the deck's race position). Iteration is bounded as prototype
 * safety; the shipped splines always cross within a fraction of the loop. */
export function muteCityTrackMarker(data: MuteCityTrackData, right: boolean, t: number, animFrame: number): { point: [number, number, number]; t: number } {
  const spline = right ? data.splineR : data.splineL;
  const chain = right ? data.chainR : data.chainL;
  jointWorldAt(data, chain, animFrame, scratchM);
  const at = (tt: number, out: [number, number, number]): void => {
    const local: [number, number, number] = [0, 0, 0];
    muteCitySplineWrapped(spline, tt, local);
    transformPoint(scratchM, local, out);
  };
  const p: [number, number, number] = [0, 0, 0];
  const q: [number, number, number] = [0, 0, 0];
  at(t, p);
  at(wrap01(t - 0.0004), q);
  const dir = p[2] > q[2] ? 0.0004 : -0.0004;
  let guard = 0;
  while ((q[2] > 0 && p[2] > 0) || (q[2] < 0 && p[2] < 0)) {
    t = wrap01(t + (p[2] < 0 ? dir : -dir));
    q[0] = p[0]; q[1] = p[1]; q[2] = p[2];
    at(t, p);
    if (++guard > 8192) break;
  }
  return { point: [f32(p[0] * data.scale), f32(p[1] * data.scale), f32(p[2] * data.scale)], t: f32(t) };
}

/** grMuteCity_801F0D20 deck construction, in world units.
 * Prototype interpretation (documented): the middle mpLib segment (0x33/id 51)
 * spans the full road width as one standable deck, so fighters never flicker on
 * the original's inter-segment gaps (which the GameCube ECB solver bridges and
 * this prototype's chain-gap logic does not). The edge rails (0x31/0x35) keep
 * their original shapes: 30-unit vertical walls in mode 1, short lip floors
 * otherwise. Rail ids stay 49/53, mid stays 51. */
export function muteCityBuildDeck(data: MuteCityTrackData, markerR: number, markerL: number, mode: 0 | 1 | 2, animFrame: number): { deck: MuteCityDeck; markerR: number; markerL: number } {
  const right = muteCityTrackMarker(data, true, markerR, animFrame);
  const left = muteCityTrackMarker(data, false, markerL, animFrame);
  const rx = right.point[0], ry = right.point[1], lx = left.point[0], ly = left.point[1];
  const floors: Floor[] = [{ id: 51, a: [f32(rx), f32(ry)], b: [f32(lx), f32(ly)], oneWay: false }];
  const surfaces: StageSurface[] = [];
  if (mode === 1) {
    surfaces.push({ id: 49, kind: 'wall', a: [f32(rx), f32(ry + 30)], b: [f32(rx), f32(ry)], oneWay: false });
    surfaces.push({ id: 53, kind: 'wall', a: [f32(lx), f32(ly)], b: [f32(lx), f32(ly + 30)], oneWay: false });
  } else if (mode === 2) {
    const angle = Math.atan2(ly - ry, lx - rx);
    const back = angle + Math.PI - 0.2617994, fwd = angle + 0.2617994;
    floors.push({ id: 49, a: [f32(rx + 10 * Math.cos(back)), f32(ry + 10 * Math.sin(back))], b: [f32(rx), f32(ry)], oneWay: false });
    floors.push({ id: 53, a: [f32(lx), f32(ly)], b: [f32(lx + 10 * Math.cos(fwd)), f32(ly + 10 * Math.sin(fwd))], oneWay: false });
  } else {
    floors.push({ id: 49, a: [f32(rx - 5), f32(ry)], b: [f32(rx), f32(ry)], oneWay: false });
    floors.push({ id: 53, a: [f32(lx), f32(ly)], b: [f32(lx + 5), f32(ly)], oneWay: false });
  }
  const deck: MuteCityDeck = { r: [right.point[0], right.point[1]], l: [left.point[0], left.point[1]], mode, floors, surfaces };
  return { deck, markerR: right.t, markerL: left.t };
}

