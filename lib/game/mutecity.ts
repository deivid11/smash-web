function parseSpline(arc: HsdArchive, jointId: number, label: string): MuteCitySpline {
  const desc = arc.pointer(jointId + 0x10);
  if (!desc) throw new Error(`Mute City ${label} spline joint has no spline.`);
  const type = arc.u8(desc), count = arc.u16(desc + 2), tension = arc.f32(desc + 4);
  if (type > 3 || count < 2 || count > 512 || !Number.isFinite(tension)) throw new Error(`Unsupported Mute City ${label} spline.`);
  const cvs = arc.pointer(desc + 8);
  arc.range(cvs, count * 12);
  const points: Array<readonly [number, number, number]> = [];
  for (let i = 0; i < count; i++) {
    const point = [arc.f32(cvs + i * 12), arc.f32(cvs + i * 12 + 4), arc.f32(cvs + i * 12 + 8)] as const;
    if (!point.every(Number.isFinite) || point.some((axis) => Math.abs(axis) > 1e7)) throw new Error(`Unsupported Mute City ${label} spline point.`);
    points.push(point);
  }
  return { type, tension, points };
}

/** All archive-bound road data: splines, the entry-30 joint tree, its animation
 * and one parsed collision set per distinct scripted area combination. The area
 * combinations are enumerated by walking the script once (table order, waits
 * ignored — they only delay effect frames, never the application order). */
export function parseMuteCityData(arc: HsdArchive, model: Pick<HsdModel, 'roots'>): MuteCityTrackData {
  const scale = arc.symbols.has('grGroundParam') ? arc.f32(arc.symbol('grGroundParam')) : 1;
  if (!Number.isFinite(scale) || scale <= 0 || scale > 5) throw new Error('Invalid Mute City stage scale.');
  const root = model.roots.find((candidate) => candidate.entry === 30);
  if (!root || root.joints.length < 10) throw new Error('Mute City road object is missing.');
  for (const hare of [5, 9]) {
    if (!(root.joints[hare]!.flags & 0x4000)) throw new Error('Mute City track spline joint is missing.');
  }
  const joints: MuteCityJoint[] = root.joints.map((joint) => ({
    parent: joint.parent, inheritScale: !!(joint.flags & 8),
    rotation: [...joint.rotation] as [number, number, number],
    scale: [...joint.scale] as [number, number, number],
    translation: [...joint.translation] as [number, number, number],
  }));
  const chain = (hare: number): number[] => {
    const path: number[] = [];
    for (let node = hare; node >= 0; node = joints[node]!.parent) {
      path.unshift(node);
      if (path.length > 128) throw new Error('Mute City joint chain is too deep.');
    }
    return path;
  };
  const clip = loadJointAnimation(arc, root.animationPointer);
  if (!clip) throw new Error('Mute City road animation is missing.');
  // Distinct area sets that persist at a frame boundary, in first-appearance
  // order (the init state leads): step a scratch runtime through one full
  // animation loop so same-frame cascades collapse to their final set.
  const scratch = createMuteCityRuntime();
  const seen = new Set<string>();
  const sets: number[][] = [];
  const record = (): void => {
    const key = scratch.areas.join(',');
    if (!seen.has(key)) { seen.add(key); sets.push([...scratch.areas]); }
  };
  record();
  for (let frame = 0; frame < MUTE_CITY_ANIM_FRAMES; frame++) {
    stepMuteCityScript(scratch, MUTE_CITY_SCRIPT, frame);
    record();
  }
  const phases = new Map<string, StageGameplayData>();
  for (const set of sets) {
    const stage = parseStageGameplay(arc, set);
    if (!stage.floors.length) throw new Error('Mute City script phase keeps no floors.');
    phases.set(set.join(','), stage);
  }
  return {
    scale,
    splineL: parseSpline(arc, root.joints[5]!.id, 'left'),
    splineR: parseSpline(arc, root.joints[9]!.id, 'right'),
    joints, clip, chainL: chain(5), chainR: chain(9), phases,
  };
}
